import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const featuredProductNames = new Set(["Premium Gift Box", "Designer Owaisi Cap", "Sidra Oudh", "Aseel", "Jannatul Ferdous"]);

async function loadEnvironment() {
  const contents = await readFile(path.join(root, ".env"), "utf8");
  for (const line of contents.split(/\r?\n/)) {
    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (match && !process.env[match[1]]) process.env[match[1]] = match[2].replace(/^['"]|['"]$/g, "");
  }
}

async function loadProducts() {
  const catalogSource = await readFile(path.join(root, "lib", "productCatalog.js"), "utf8");
  const moduleUrl = `data:text/javascript;base64,${Buffer.from(catalogSource).toString("base64")}`;
  return (await import(moduleUrl)).allProducts;
}

function slugify(value) {
  return value.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function sqlText(value) {
  if (value === null || value === undefined || value === "") return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlJsonb(value) {
  if (value === null || value === undefined) return "null";
  return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
}

async function uploadWithRetry(sourcePath, fileName, privateKey) {
  const fileBuffer = await readFile(sourcePath);
  let lastError;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const body = new FormData();
      body.append("file", new Blob([fileBuffer]), fileName);
      body.append("fileName", fileName);
      body.append("folder", "/sidra-store/products");
      body.append("useUniqueFileName", "false");
      body.append("overwriteFile", "true");
      body.append("tags", "sidra-store,product");
      const response = await fetch("https://upload.imagekit.io/api/v1/files/upload", {
        method: "POST",
        headers: { Authorization: `Basic ${Buffer.from(`${privateKey}:`).toString("base64")}` },
        body,
      });
      const payload = await response.json();
      if (!response.ok) throw new Error(`ImageKit upload failed (${response.status}): ${JSON.stringify(payload)}`);
      return payload.url;
    } catch (error) {
      lastError = error;
      if (attempt < 3) await new Promise((resolve) => setTimeout(resolve, attempt * 1000));
    }
  }
  throw lastError;
}

function buildSeedSql(products, imageUrls) {
  const categoryMap = new Map();
  for (const product of products) {
    const categorySlug = slugify(product.category);
    if (!categoryMap.has(categorySlug)) categoryMap.set(categorySlug, { name: product.category, subcategories: new Map() });
    const subcategorySlug = slugify(product.subCategory);
    categoryMap.get(categorySlug).subcategories.set(subcategorySlug, product.subCategory);
  }

  const lines = [
    "-- Generated by scripts/upload-product-images.mjs.",
    "-- Run after migrations 001 through 006.",
    "",
  ];
  let categoryOrder = 1;
  for (const [categorySlug, category] of categoryMap) {
    lines.push(`insert into public.categories (name, slug, sort_order, is_active) values (${sqlText(category.name)}, ${sqlText(categorySlug)}, ${categoryOrder}, true) on conflict (slug) do update set name = excluded.name, is_active = true;`);
    let subcategoryOrder = 1;
    for (const [subcategorySlug, subcategoryName] of category.subcategories) {
      lines.push(`insert into public.subcategories (category_id, name, slug, sort_order, is_active) select id, ${sqlText(subcategoryName)}, ${sqlText(subcategorySlug)}, ${subcategoryOrder}, true from public.categories where slug = ${sqlText(categorySlug)} on conflict (category_id, slug) do update set name = excluded.name, is_active = true;`);
      subcategoryOrder += 1;
    }
    categoryOrder += 1;
  }

  lines.push("");
  for (const product of products) {
    const slug = slugify(product.name);
    const categorySlug = slugify(product.category);
    const subcategorySlug = slugify(product.subCategory);
    const imageUrl = imageUrls[product.src];
    const variantsJson = sqlJsonb(product.variants || []);
    lines.push(
      "insert into public.products (category_id, subcategory_id, name, slug, short_description, description, price, stock_quantity, image_url, badge, is_featured, is_active, variants) " +
      `select categories.id, subcategories.id, ${sqlText(product.name)}, ${sqlText(slug)}, ${sqlText(product.desc)}, ${sqlText(product.desc)}, ${Number(product.price)}, 100, ${sqlText(imageUrl)}, ${sqlText(product.badge)}, ${featuredProductNames.has(product.name) ? "true" : "false"}, true, ${variantsJson} ` +
      `from public.categories join public.subcategories on subcategories.category_id = categories.id and subcategories.slug = ${sqlText(subcategorySlug)} where categories.slug = ${sqlText(categorySlug)} ` +
      "on conflict (slug) do update set category_id = excluded.category_id, subcategory_id = excluded.subcategory_id, name = excluded.name, short_description = excluded.short_description, description = excluded.description, price = excluded.price, image_url = excluded.image_url, badge = excluded.badge, is_featured = excluded.is_featured, is_active = true, variants = excluded.variants;",
    );
  }
  return `${lines.join("\n")}\n`;
}

async function main() {
  await loadEnvironment();
  const privateKey = process.env.IMAGEKIT_PRIVATE_KEY;
  if (!privateKey) throw new Error("IMAGEKIT_PRIVATE_KEY is missing from .env.");
  const products = await loadProducts();
  const uniqueSources = [...new Set(products.map((product) => product.src))];
  const imageUrls = {};

  for (let index = 0; index < uniqueSources.length; index += 1) {
    const source = uniqueSources[index];
    const extension = path.extname(source).toLowerCase() || ".jpg";
    const digest = createHash("sha1").update(source).digest("hex").slice(0, 8);
    const fileName = `${slugify(path.basename(source, extension))}-${digest}${extension}`;
    const localPath = path.join(root, "public", ...decodeURIComponent(source).replace(/^\//, "").split("/"));
    process.stdout.write(`[${index + 1}/${uniqueSources.length}] Uploading ${source}\n`);
    imageUrls[source] = await uploadWithRetry(localPath, fileName, privateKey);
  }

  await mkdir(path.join(root, "supabase", "data"), { recursive: true });
  await writeFile(path.join(root, "supabase", "data", "imagekit-product-urls.json"), `${JSON.stringify(imageUrls, null, 2)}\n`);
  await writeFile(path.join(root, "supabase", "migrations", "007_seed_product_catalog.sql"), buildSeedSql(products, imageUrls));
  process.stdout.write(`Uploaded ${uniqueSources.length} unique images and generated the product seed migration.\n`);
}

await main();
