import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const featuredProductNames = new Set(["Premium Gift Box", "Designer Owaisi Cap", "Sidra Oudh", "Aseel", "Jannatul Ferdous"]);

async function loadProducts() {
  const catalogSource = await readFile(path.join(root, "lib", "productCatalog.js"), "utf8");
  const moduleUrl = `data:text/javascript;base64,${Buffer.from(catalogSource).toString("base64")}`;
  return (await import(moduleUrl)).allProducts;
}

function slugify(value) {
  return value.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function sqlText(value) {
  if (value === null || value === undefined || value === "") return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlJsonb(value) {
  if (value === null || value === undefined) return "null";
  return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
}

async function main() {
  const products = await loadProducts();
  
  // Load existing image URLs if available
  let imageUrls = {};
  try {
    const urlsFile = path.join(root, "supabase", "data", "imagekit-product-urls.json");
    imageUrls = JSON.parse(await readFile(urlsFile, "utf8"));
  } catch {
    console.log("No existing image URLs found, using placeholders");
  }

  // For products without images, use a placeholder
  const placeholderUrl = "https://ik.imagekit.io/w9zavcqhb/sidra-store/products/attar.jpg";
  
  const categoryMap = new Map();
  for (const product of products) {
    const categorySlug = slugify(product.category);
    if (!categoryMap.has(categorySlug)) categoryMap.set(categorySlug, { name: product.category, subcategories: new Map() });
    const subcategorySlug = slugify(product.subCategory);
    categoryMap.get(categorySlug).subcategories.set(subcategorySlug, product.subCategory);
  }

  const lines = [
    "-- Generated by scripts/generate-seed-sql.mjs",
    "-- Run after migrations 001 through 012.",
    "",
  ];
  let categoryOrder = 1;
  for (const [categorySlug, category] of categoryMap) {
    lines.push(`insert into public.categories (name, slug, sort_order, is_active) values (${sqlText(category.name)}, ${sqlText(categorySlug)}, ${categoryOrder}, true) on conflict (slug) do update set name = excluded.name, is_active = true;`);
    let subcategoryOrder = 1;
    for (const [subcategorySlug, subcategoryName] of category.subcategories) {
      lines.push(`insert into public.subcategories (category_id, name, slug, sort_order, is_active) select id, ${sqlText(subcategoryName)}, ${sqlText(subcategorySlug)}, ${subcategoryOrder}, true from public.categories where slug = ${sqlText(categorySlug)} on conflict (category_id, slug) do update set name = excluded.name, is_active = true;`);
      subcategoryOrder += 1;
    }
    categoryOrder += 1;
  }

  lines.push("");
  for (const product of products) {
    const slug = slugify(product.name);
    const categorySlug = slugify(product.category);
    const subcategorySlug = slugify(product.subCategory);
    const imageUrl = imageUrls[product.src] || placeholderUrl;
    const variantsJson = sqlJsonb(product.variants || []);
    lines.push(
      "insert into public.products (category_id, subcategory_id, name, slug, short_description, description, price, stock_quantity, image_url, badge, is_featured, is_active, variants) " +
      `select categories.id, subcategories.id, ${sqlText(product.name)}, ${sqlText(slug)}, ${sqlText(product.desc)}, ${sqlText(product.desc)}, ${Number(product.price)}, 100, ${sqlText(imageUrl)}, ${sqlText(product.badge)}, ${featuredProductNames.has(product.name) ? "true" : "false"}, true, ${variantsJson} ` +
      `from public.categories join public.subcategories on subcategories.category_id = categories.id and subcategories.slug = ${sqlText(subcategorySlug)} where categories.slug = ${sqlText(categorySlug)} ` +
      "on conflict (slug) do update set category_id = excluded.category_id, subcategory_id = excluded.subcategory_id, name = excluded.name, short_description = excluded.short_description, description = excluded.description, price = excluded.price, image_url = excluded.image_url, badge = excluded.badge, is_featured = excluded.is_featured, is_active = true, variants = excluded.variants;",
    );
  }

  await mkdir(path.join(root, "supabase", "migrations"), { recursive: true });
  await writeFile(path.join(root, "supabase", "migrations", "007_seed_product_catalog.sql"), `${lines.join("\n")}\n`);
  console.log(`Generated seed migration with ${products.length} products.`);
}

await main();
